    ''')
    code('''
    selection = json.loads((RUN / 'selection.json').read_text())
    assert selection['holdout_used_for_selection'] is False
    print('Settings selected on 2013 only:', selection['selected'])
    display(pd.read_csv(RUN / 'validation_candidates.csv'))
    ''')
    code('''
    predictions = pd.read_csv(RUN / 'predictions.csv', parse_dates=['origin_time', 'target_time'], float_precision='round_trip')
    assert not predictions.duplicated(['phase', 'model', 'origin_time']).any()
    assert (predictions.target_time - predictions.origin_time).dt.total_seconds().eq(3600).all()
    for phase, period in predictions.groupby('phase'):
        reference = None
